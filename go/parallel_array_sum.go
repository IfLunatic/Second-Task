// runSmallTest виконує тест і виводить результат.
func runSmallTest(name string, data []int64, expected int64) {
	// Копія для послідовної версії
	seqArr := copyArray(data)
	seqResult := sequentialWaveSum(seqArr)

	// Копія для паралельної версії
	parArr := copyArray(data)
	parResult := parallelWaveSum(parArr, runtime.NumCPU())

	seqOk := "OK"
	if seqResult != expected {
		seqOk = "ПОМИЛКА"
	}
	parOk := "OK"
	if parResult != expected {
		parOk = "ПОМИЛКА"
	}
	match := "Так"
	if seqResult != parResult {
		match = "НІ"
	}

	fmt.Printf("  %-25s | Очік: %4d | Послід: %4d [%s] | Парал: %4d [%s] | Збіг: %s\n",
		name, expected, seqResult, seqOk, parResult, parOk, match)
}

