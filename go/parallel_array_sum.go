// Лабораторна робота: Багатопотоковий алгоритм обчислення суми масиву
// методом хвильової редукції (wave reduction).
//
// Алгоритм:
//   1. Маємо масив з N елементів.
//   2. На кожній хвилі: array[i] = array[i] + array[j], де j = n - 1 - i.
//   3. Якщо n непарне — середній елемент лишається без змін.
//   4. Після хвилі актуальна довжина стає ceil(n / 2).
//   5. Повторюємо, поки довжина не стане 1. array[0] — сума.
//
// Мова: Go
// Тип даних: int64 (64-бітне знакове ціле).

package main

import (
	"fmt"
	"runtime"
	"sync"
	"time"
)

// ========================================================================
// WorkItem — структура для передачі завдання робочій goroutine через канал.
// Містить діапазон індексів пар та актуальну довжину масиву.
// ========================================================================
type WorkItem struct {
	StartIdx int // Початковий індекс діапазону пар (включно)
	EndIdx   int // Кінцевий індекс діапазону пар (не включно)
	N        int // Актуальна довжина масиву на поточній хвилі
}

// ========================================================================
// Послідовна (однопотокова) версія алгоритму хвильової редукції
// ========================================================================

// sequentialWaveSum обчислює суму масиву послідовно.
// Масив модифікується на місці (in-place).
func sequentialWaveSum(array []int64) int64 {
	// Актуальна довжина — спочатку це повна довжина слайсу
	n := len(array)

	// Якщо масив порожній — сума 0
	if n == 0 {
		return 0
	}

	// Хвильовий цикл: працюємо, поки актуальна довжина > 1
	for n > 1 {
		// Кількість пар на цій хвилі
		pairs := n / 2

		// Обробляємо кожну пару: i та симетричний j
		for i := 0; i < pairs; i++ {
			j := n - 1 - i                    // Симетричний індекс
			array[i] = array[i] + array[j]     // Додаємо й записуємо в менший індекс
		}
		// Якщо n непарне, середній елемент (індекс n/2) лишається без змін.

		// Нова актуальна довжина: ceil(n / 2) = (n + 1) / 2
		n = (n + 1) / 2
	}

	// Після всіх хвиль array[0] містить суму
	return array[0]
}

// ========================================================================
// Паралельна (багатопотокова) версія алгоритму хвильової редукції
// ========================================================================

// parallelWaveSum обчислює суму масиву паралельно.
//
// Використовує фіксовану кількість робочих goroutine (worker pool pattern).
// Горутини створюються ОДИН раз і використовуються повторно для всіх хвиль.
//
// Горутина (goroutine) vs системний потік:
//   - Горутина — це легковісний "зелений потік", керований Go Runtime.
//   - Початковий розмір стеку горутини: ~2-8 КБ (у потоку ОС: ~1-8 МБ).
//   - Можна створити мільйони горутин (потоків ОС — тисячі).
//   - Go Runtime мультиплексує горутини на M системних потоків (модель M:N).
//   - runtime.GOMAXPROCS(n) встановлює кількість потоків ОС, на яких
//     виконуються горутини (за замовчуванням = кількість CPU).
//
// Канал (channel):
//   - Механізм комунікації між горутинами. Типізований.
//   - Буферизований канал: make(chan T, capacity) — відправник не блокується,
//     поки в каналі є місце. Приймач не блокується, поки канал не порожній.
//   - Небуферизований канал: make(chan T) — відправник блокується, поки
//     приймач не прочитає значення (синхронна передача).
//   - close(ch) — закриває канал. Приймач отримає нульове значення
//     і false як другий результат. Цикл range автоматично завершиться.
//
// sync.WaitGroup:
//   - Лічильник для очікування завершення групи горутин.
//   - Add(n) — збільшує лічильник на n.
//   - Done() — зменшує лічильник на 1 (еквівалент Add(-1)).
//   - Wait() — блокує, поки лічильник не стане 0.
//   - Аналог CountDownLatch у Java.
func parallelWaveSum(array []int64, numWorkers int) int64 {
	n := len(array)

	// Якщо масив порожній або з одного елемента — паралелізм зайвий
	if n == 0 {
		return 0
	}
	if n == 1 {
		return array[0]
	}

	// Встановлюємо кількість потоків ОС для Go Runtime.
	// GOMAXPROCS визначає, скільки горутин може виконуватися одночасно.
	runtime.GOMAXPROCS(numWorkers)

	// --- Створення буферизованого каналу для передачі завдань ---
	// Буфер = numWorkers, щоб керуючий потік міг відправити кілька
	// завдань без блокування (поки робочі горутини забирають попередні).
	workChan := make(chan WorkItem, numWorkers)

	// WaitGroup для синхронізації між хвилями
	var wg sync.WaitGroup

	// --- Запуск робочих горутин (один раз) ---
	// Кожна горутина працює в нескінченному циклі, читаючи з каналу.
	// Коли канал закривається — цикл range завершується, горутина виходить.
	for w := 0; w < numWorkers; w++ {
		go func() {
			// Горутина читає завдання з каналу, поки він не закритий.
			// range по каналу: кожна ітерація блокується, поки не з'явиться
			// нове значення або канал не закриється.
			for work := range workChan {
				// Обробляємо діапазон пар [StartIdx, EndIdx)
				for i := work.StartIdx; i < work.EndIdx; i++ {
					j := work.N - 1 - i              // Симетричний індекс
					array[i] = array[i] + array[j]    // Додаємо й записуємо
				}
				// Повідомляємо про завершення чанка
				wg.Done()
			}
		}()
	}

	// --- Хвильовий цикл (керуючий потік — main goroutine) ---
	for n > 1 {
		// Кількість пар на цій хвилі
		pairs := n / 2

		// Кількість чанків — не більше, ніж пар
		numChunks := numWorkers
		if numChunks > pairs {
			numChunks = pairs
		}

		// --- Розподіл пар між чанками ---
		baseChunkSize := pairs / numChunks
		remainder := pairs % numChunks

		// Додаємо в WaitGroup кількість чанків, які будуть відправлені.
		// ВАЖЛИВО: Add() потрібно викликати ДО відправки в канал,
		// інакше Wait() може завершитися передчасно.
		wg.Add(numChunks)

		currentStart := 0
		for t := 0; t < numChunks; t++ {
			// Розмір чанка: базовий + 1, якщо є залишок
			chunkSize := baseChunkSize
			if t < remainder {
				chunkSize++
			}
			endIdx := currentStart + chunkSize

			// Відправляємо завдання в канал
			// Якщо буфер повний — блокуємося, поки робоча горутина
			// не забере попереднє завдання.
			workChan <- WorkItem{
				StartIdx: currentStart,
				EndIdx:   endIdx,
				N:        n,
			}

			currentStart = endIdx
		}

		// --- Очікування завершення всіх чанків поточної хвилі ---
		// Wait() блокує, поки всі горутини не викличуть Done().
		// Це гарантує: наступна хвиля не почнеться, поки всі пари
		// поточної хвилі не будуть оброблені.
		wg.Wait()

		// Нова актуальна довжина
		n = (n + 1) / 2
	}

	// --- Закриття каналу ---
	// close() сигналізує робочим горутинам, що нових завдань більше не буде.
	// Цикл range у горутинах завершиться, і вони вийдуть.
	// ВАЖЛИВО: закриваємо канал тільки після завершення всіх хвиль.
	close(workChan)

	return array[0]
}

