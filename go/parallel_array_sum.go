// createArray створює слайс з int64 зі значеннями від 1 до size.
func createArray(size int) []int64 {
	array := make([]int64, size)
	for i := 0; i < size; i++ {
		array[i] = int64(i + 1) // Елементи: 1, 2, 3, ..., size
	}
	return array
}

// copyArray створює копію слайсу (бо алгоритм модифікує слайс на місці).
func copyArray(source []int64) []int64 {
	dest := make([]int64, len(source))
	copy(dest, source)
	return dest
}

